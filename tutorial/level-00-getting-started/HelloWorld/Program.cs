
// This program teaches us how to display text using C#.

// Console.WriteLine() tells the computer to display a message.
// The words inside double quotation marks are the message.
Console.WriteLine("Hello, World!");

// This line displays another message on a new line.
Console.WriteLine("I am learning C#.");

// This line displays a third message.
Console.WriteLine("I can teach a computer what to do.");

//this is the numeric addition of 3 + 3
Console.WriteLine(3 + 3);


// The program finishes after executing these instructions.


